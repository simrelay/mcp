#!/usr/bin/env node
// Bakes the OAuth client ID, API base URL, and build flavor into
// src/build-config.ts and patches manifest.json. Run by CI before `npm run build`.
//
// Reads:
//   SIMRELAY_OAUTH_CLIENT_ID  (required) — the client ID to embed
//   BUILD_FLAVOR              (optional) — "test" | "prod" | "dev" (default "dev")
//   SIMRELAY_API_BASE_URL     (optional) — override the per-flavor default URL
//   BUILD_VERSION             (optional) — override the manifest version (e.g. "2.1.0" from a git tag)
//   GITHUB_SHA                (optional) — used to suffix test-flavor versions
//
// Per-flavor API base URL defaults (mirrors the SimRelay mobile/Chrome clients):
//   test → https://test.simrelay.com
//   prod → https://simrelay.com
//   dev  → null (server falls back to env or hardcoded default)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// import.meta.dirname is Node 21.2+; derive it for Node 20 compatibility.
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const clientId = process.env.SIMRELAY_OAUTH_CLIENT_ID;
if (!clientId) {
  console.error("ERROR: SIMRELAY_OAUTH_CLIENT_ID is not set");
  process.exit(1);
}

const flavor = process.env.BUILD_FLAVOR ?? "dev";
if (!["dev", "test", "prod"].includes(flavor)) {
  console.error(`ERROR: BUILD_FLAVOR must be one of dev|test|prod (got ${flavor})`);
  process.exit(1);
}

const FLAVOR_BASE_URLS = {
  test: "https://test.simrelay.com",
  prod: "https://simrelay.com",
  dev: null,
};

const apiBaseUrl =
  process.env.SIMRELAY_API_BASE_URL ?? FLAVOR_BASE_URLS[flavor];

// 1) src/build-config.ts
const ts = `// AUTO-GENERATED by scripts/inject-build-config.mjs — do not edit.
export const BUILDTIME_CLIENT_ID: string | null = ${JSON.stringify(clientId)};
export const BUILDTIME_API_BASE_URL: string | null = ${JSON.stringify(apiBaseUrl)};
export const BUILD_FLAVOR: "dev" | "test" | "prod" = ${JSON.stringify(flavor)};
`;
writeFileSync(resolve(root, "src/build-config.ts"), ts);

// 2) manifest.json patch (distinct name + display_name + version per flavor)
const manifestPath = resolve(root, "manifest.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));

const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const baseVersion = pkg.version;

if (flavor === "test") {
  manifest.name = "simrelay-mcp-test";
  manifest.display_name = "SimRelay (test)";
  const sha = (process.env.GITHUB_SHA ?? "local").slice(0, 7);
  manifest.version = process.env.BUILD_VERSION ?? `${baseVersion}-test.${sha}`;
} else if (flavor === "prod") {
  manifest.name = "simrelay-mcp";
  manifest.display_name = "SimRelay";
  manifest.version = (process.env.BUILD_VERSION ?? baseVersion).replace(/^v/, "");
} else {
  // dev — leave manifest name as-is
  manifest.version = process.env.BUILD_VERSION ?? baseVersion;
}

writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

console.error(
  `Injected build config: flavor=${flavor} client_id=${clientId.slice(0, 8)}… api_base_url=${apiBaseUrl ?? "(none)"} version=${manifest.version}`,
);
